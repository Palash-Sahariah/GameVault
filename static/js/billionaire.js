const list =
    document.getElementById("billionaireList");

const searchInput =
    document.getElementById("billionaireSearch");

const clearButton =
    document.getElementById("clearSearch");

const resultCount =
    document.getElementById("resultCount");

const searchStatus =
    document.getElementById("searchStatus");

const noResults =
    document.getElementById("noResults");

const searchedName =
    document.getElementById("searchedName");



/* =========================================
   RENDER BILLIONAIRES
========================================= */

function renderBillionaires(data) {

    list.innerHTML = "";

    resultCount.textContent = data.length;


    if (data.length === 0) {

        list.style.display = "none";

        noResults.classList.remove("hidden");

        searchedName.textContent =
            `"${searchInput.value.trim()}"`;

        searchStatus.textContent = "";

        return;
    }


    list.style.display = "grid";

    noResults.classList.add("hidden");


    if (searchInput.value.trim() !== "") {

        searchStatus.textContent =
            `${data.length} result${data.length === 1 ? "" : "s"} found`;

    } else {

        searchStatus.textContent = "";

    }


    data.forEach(person => {

        const card =
            document.createElement("article");

        card.className =
            "billionaire-card";


        const imageHTML =
            person.image
                ? `
                    <img
                        src="${person.image}"
                        alt="${person.name}"
                        class="billionaire-image"
                        onerror="this.style.display='none'; this.nextElementSibling.style.display='flex';"
                    >

                    <div
                        class="billionaire-initials"
                        style="display:none;"
                    >
                        ${getInitials(person.name)}
                    </div>
                `
                : `
                    <div class="billionaire-initials">
                        ${getInitials(person.name)}
                    </div>
                `;


        card.innerHTML = `

            <div class="rank-box">
                #${person.rank}
            </div>

            <div class="billionaire-photo">
                ${imageHTML}
            </div>

            <div class="billionaire-info">

                <span class="billionaire-small-label">
                    BILLIONAIRE
                </span>

                <h3>
                    ${person.name}
                </h3>

                <span class="billionaire-estimate">
                    ESTIMATED NET WORTH
                </span>

            </div>

            <div class="billionaire-fortune">

                <strong>
                    $${formatNumber(person.netWorth)}B
                </strong>

                <button
                    class="select-button"
                    data-id="${person.id}"
                >
                    SELECT
                </button>

            </div>

        `;


        list.appendChild(card);

    });


    document
        .querySelectorAll(".select-button")
        .forEach(button => {

            button.addEventListener(
                "click",
                function() {

                    const id =
                        this.dataset.id;

                    window.location.href =
                        `/games/billionaire/play?id=${encodeURIComponent(id)}`;

                }
            );

        });

}



/* =========================================
   SEARCH
========================================= */

function searchBillionaires() {

    const query =
        searchInput.value
            .trim()
            .toLowerCase();


    if (!query) {

        renderBillionaires(billionaires);

        return;

    }


    const filtered =
        billionaires.filter(person => {

            const name =
                person.name.toLowerCase();

            return name.includes(query);

        });


    renderBillionaires(filtered);

}



/* =========================================
   HELPERS
========================================= */

function formatNumber(number) {

    return number
        .toString()
        .replace(
            /\B(?=(\d{3})+(?!\d))/g,
            ","
        );

}


function getInitials(name) {

    const cleanName =
        name
            .replace("& family", "")
            .trim()
            .split(" ");


    const first =
        cleanName[0]?.charAt(0) || "";


    const last =
        cleanName.length > 1
            ? cleanName[cleanName.length - 1]
                .replace(/[^\w]/g, "")
                .charAt(0)
            : "";


    return (
        first + last
    ).toUpperCase();

}



/* =========================================
   EVENTS
========================================= */

searchInput.addEventListener(
    "input",
    searchBillionaires
);


clearButton.addEventListener(
    "click",
    function() {

        searchInput.value = "";

        searchInput.focus();

        renderBillionaires(billionaires);

    }
);


